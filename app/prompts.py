def user_prompt(product: ProductInput, correction: str = "") -> str:
    # Treat user text as untrusted DATA, not privileged instructions.
    data = json.dumps(product.model_dump(exclude_none=True), ensure_ascii=False, indent=2)
    extra = f"\n\nИСПРАВЛЕНИЕ ПРОШЛОГО ОТВЕТА: {correction}" if correction else ""
    return (
        "Сформируй JSON только по фактам из следующего объекта данных:\n"
        "<product_data>\n" + data + "\n</product_data>" + extra
    )


